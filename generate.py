# ── Blog article index ─────────────────────────────────────────────────────────

def _load_blog_articles() -> list[dict]:
    """Load written articles from seo_articles table."""
    articles = []
    if not MKTG_DB.exists():
        return articles
    try:
        with sqlite3.connect(MKTG_DB) as con:
            rows = con.execute(
                "SELECT slug, keyword, category, title, created_at "
                "FROM seo_articles ORDER BY created_at DESC"
            ).fetchall()
        for r in rows:
            slug     = r[0]
            html_path = BLOG_DIR / f"{slug}.html"
            if not html_path.exists():
                continue
            # Read meta_description from file quickly
            meta_desc = ""
            try:
                text = html_path.read_text(encoding="utf-8", errors="ignore")
                import re
                m = re.search(r'<meta name="description" content="([^"]*)"', text)
                if m:
                    meta_desc = m.group(1)
            except Exception:
                pass
            articles.append({
                "slug":     slug,
                "keyword":  r[1],
                "category": (r[2] or "").replace("_", " ").title(),
                "title":    r[3] or r[1].title(),
                "date":     r[4][:10] if r[4] else "",
                "meta":     meta_desc[:120],
            })
    except Exception:
        pass
    return articles


