def _load_products() -> list[dict]:
    if not DB_PATH.exists():
        return []
    products: list[dict] = []
    with sqlite3.connect(DB_PATH) as con:
        con.row_factory = sqlite3.Row
        try:
            for r in con.execute(
                "SELECT title, product_type, price_cents, trend_topic, "
                "description, listing_url, status, created_at "
                "FROM muse_products "
                "WHERE status IN ('draft','published','ready') "
                "ORDER BY created_at DESC"
            ).fetchall():
                topic = (r["trend_topic"] or "General")
                products.append({
                    "title":       r["title"],
                    "type":        r["product_type"].replace("_", " ").title(),
                    "price":       r["price_cents"] / 100,
                    "topic":       topic,
                    "description": (r["description"] or "")[:280],
                    "url":         r["listing_url"] or STORE_URL,
                    "status":      r["status"],
                    "source":      "MUSE",
                    "asin":        "",
                })
        except Exception:
            pass
        try:
            for r in con.execute(
                "SELECT title, description, listing_url, price_cents, status "
                "FROM lens_reports WHERE status IN ('draft','published') "
                "ORDER BY created_at DESC"
            ).fetchall():
                products.append({
                    "title":       r["title"],
                    "type":        "Market Report",
                    "price":       (r["price_cents"] or 0) / 100,
                    "topic":       "Geopolitical",
                    "description": (r["description"] or "")[:280],
                    "url":         r["listing_url"] or STORE_URL,
                    "status":      r["status"],
                    "source":      "LENS",
                    "asin":        "",
                })
        except Exception:
            pass

    # Load ASINs from book_registry.json if present
    registry_path = Path("database") / "book_registry.json"
    registry: dict = {}
    if registry_path.exists():
        try:
            registry = json.loads(registry_path.read_text(encoding="utf-8"))
        except Exception:
            pass
    for p in products:
        reg = registry.get(p["title"], {})
        if reg.get("asin"):
            p["asin"] = reg["asin"]

    return products


